export type Locale = "en" | "ar";

type Dict = Record<string, unknown>;

function interpolate(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`));
}

function flatten(dict: Dict, prefix = ""): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(dict)) {
    const path = prefix ? `${prefix}.${k}` : k;
    if (typeof v === "string") out[path] = v;
    else if (v && typeof v === "object") Object.assign(out, flatten(v as Dict, path));
  }
  return out;
}

let enFlat: Record<string, string> | null = null;
let arFlat: Record<string, string> | null = null;

function tables() {
  if (!enFlat || !arFlat) {
    enFlat = flatten(en);
    arFlat = flatten(ar);
  }
  return { enFlat, arFlat };
}

export function translate(locale: Locale, key: string, vars?: Record<string, string | number>) {
  const { enFlat: english, arFlat: arabic } = tables();
  const table = locale === "ar" ? arabic : english;
  return interpolate(table[key] ?? english[key] ?? key, vars);
}

